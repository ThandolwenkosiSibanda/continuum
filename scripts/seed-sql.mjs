// Prints SQL that loads src/data into the Supabase tables (supabase/schema.sql).
//   npm run seed-sql   → writes supabase/seed.sql
// The SQL empties the tables first, so running it again replaces their content.

import { industries } from "../src/data/industries.js";
import { posts } from "../src/data/posts.js";
import { processSteps } from "../src/data/processSteps.js";
import { projects } from "../src/data/projects.js";
import { services } from "../src/data/services.js";

// Columns holding lists of objects; every other list is a text[].
const JSONB = new Set(["features", "screens", "why", "included", "steps", "faq", "body"]);

const text = (s) => `'${String(s).replace(/'/g, "''")}'`;

function literal(column, value) {
  if (value == null) return "null";
  if (JSONB.has(column)) return `${text(JSON.stringify(value))}::jsonb`;
  if (Array.isArray(value)) return value.length ? `array[${value.map(text).join(", ")}]` : "'{}'::text[]";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return text(value);
}

function inserts(table, rows) {
  return rows.map((row) => {
    const columns = Object.keys(row);
    const values = columns.map((c) => literal(c, row[c]));
    return `insert into ${table} (${columns.join(", ")}) values (${values.join(", ")});`;
  });
}

const sql = [
  "-- Generated by scripts/seed-sql.mjs from src/data. Don't edit by hand.",
  "begin;",
  "truncate posts, process_steps, services, projects, industries restart identity cascade;",
  ...inserts("industries", industries),
  ...inserts("projects", projects),
  ...inserts("services", services),
  ...inserts("process_steps", processSteps),
  ...inserts("posts", posts),
  "commit;",
];

console.log(sql.join("\n"));
